# Функция для поиска индекса товара
def find_index(items, target):
    #Возвращает индекс первого вхождения target в списке items.
    #Если target не найден, возвращает None.
    # enumerate возвращает пары (индекс, элемент) для каждого элемента списка
    for i, item in enumerate(items):
        # Сравниваем текущий элемент с искомым товаром
        if item == target:
            # Если нашли — сразу возвращаем индекс
            return i
    # Если цикл завершился без return, значит элемент не найден
    # Возвращаем None
    return None
items_list = ['яблоко', 'банан', 'апельсин', 'груша', 'киви', 'банан']

# Перебираем товары, которые нужно найти
for find_item in ['банан', 'груша', 'персик']:
    # Вызываем нашу функцию, передаём список и искомый товар
    index_item = find_index(items_list, find_item)
    # Проверяем, найден ли товар (функция вернула None или индекс)
    if index_item is not None:
        # Если индекс существует — выводим результат с индексом первого вхождения
        print(f"Первое вхождение товара '{find_item}' имеет индекс {index_item}.")
    else:
        # Если товар не найден — сообщаем об этом
        print(f"Товар '{find_item}' не найден в списке.")
